(function () {
  const norm = s => String(s || '').toLowerCase().replace(/[\s・\-ー_'’.]/g, '');
  GLOSSARY.forEach(g => { g._keys = [g.jp, g.en, ...g.alias].map(norm).filter(Boolean); });
  window.matchGloss = function (q, limit) {
    const k = norm(q); if (!k) return [];
    const scored = [];
    GLOSSARY.forEach(g => {
      let sc = 0;
      for (const key of g._keys) {
        if (key === k) sc = Math.max(sc, 100);
        else if (k.length >= 2 && key.startsWith(k)) sc = Math.max(sc, 60);
        else if (k.length >= 2 && key.includes(k)) sc = Math.max(sc, 40);
        else if (key.length >= 3 && k.includes(key)) sc = Math.max(sc, 30);
      }
      if (sc) scored.push([sc, g]);
    });
    scored.sort((a, b) => b[0] - a[0]);
    return scored.slice(0, limit || 4).map(x => x[1]);
  };
})();
